import { createThemesFor } from '@atb-as/theme';
import { currentOrg, getOrgDataFor, WEBSHOP_ORGS } from '@atb/modules/org-data';
import { useEffect, useSyncExternalStore } from 'react';
import { getThemeVariant } from './theme-variant';

/**
 * Lets developers preview the colors of another org while running `next dev`,
 * without restarting with a different NEXT_PUBLIC_PLANNER_ORG_ID.
 *
 * Follows the previewed org: colors, `featureConfig.forceTheme` (forced
 * light/dark mode and whether the dark mode toggle is shown), the county
 * (fylkeskommune) logo, the county name in the footer, and the org-specific
 * icon variants in the header and footer.
 *
 * Stays as for the current org: texts, URLs, other feature config and
 * anything read through `getOrgData()` or the static `theme` export.
 */
export const isDevOrgThemeEnabled = process.env.NODE_ENV === 'development';

const STYLE_ELEMENT_ID = 'dev-org-theme';

type OrgTheme = ReturnType<typeof createThemesFor>;
const devOrgThemeCache: Partial<Record<WEBSHOP_ORGS, OrgTheme>> = {};

const listeners = new Set<() => void>();

// Kept in memory only, so the preview resets on page reload.
let devOrg: WEBSHOP_ORGS | undefined;

function getDevOrgSnapshot() {
  return devOrg;
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function setDevOrg(org: WEBSHOP_ORGS | undefined) {
  devOrg = org === currentOrg ? undefined : org;
  listeners.forEach((listener) => listener());
}

/**
 * The org whose colors are previewed, or undefined when using the current
 * org. Always undefined on the server, during hydration and in production
 * builds, where it doesn't subscribe to anything.
 */
export const useDevOrg: () => WEBSHOP_ORGS | undefined = isDevOrgThemeEnabled
  ? useStoredDevOrg
  : () => undefined;

function useStoredDevOrg() {
  return useSyncExternalStore(subscribe, getDevOrgSnapshot, () => undefined);
}

/**
 * The org data of the previewed org, or of the current org when not
 * previewing another org.
 */
export function useThemeOrgData() {
  return getOrgDataFor(useDevOrg() ?? currentOrg);
}

/**
 * The theme of the previewed org, or undefined when not previewing another
 * org.
 */
export function useDevOrgTheme(): OrgTheme | undefined {
  const devOrg = useDevOrg();
  if (!devOrg) return undefined;
  return (devOrgThemeCache[devOrg] ??= createThemesFor(
    getThemeVariant(devOrg),
  ));
}

/**
 * Override the color CSS variables from the org theme.css with the colors of
 * the previewed org. The variable names match those generated by
 * @atb-as/theme and used by the token() PostCSS function.
 */
export function useDevOrgThemeStyles() {
  const theme = useDevOrgTheme();

  useEffect(() => {
    if (!theme) return;

    const style = document.createElement('style');
    style.id = STYLE_ELEMENT_ID;
    style.textContent = (['light', 'dark'] as const)
      .map(
        (mode) =>
          `:root[data-theme="${mode}"] {\n${toCssVariables(theme[mode].color, ['color']).join('\n')}\n}`,
      )
      .join('\n');
    document.head.appendChild(style);
    return () => style.remove();
  }, [theme]);
}

function toCssVariables(value: object, path: string[]): string[] {
  return Object.entries(value).flatMap(([key, child]) => {
    const childPath = [...path, camelToKebab(key)];
    return typeof child === 'object' && child !== null
      ? toCssVariables(child, childPath)
      : [`  --${childPath.join('-')}: ${child};`];
  });
}

function camelToKebab(str: string) {
  return str.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
}
